"""Document 13 (SPEC-EBMR-004) — Genealogy & Traceability Engine. New module. See migration
<pending>_0014_genealogy_schema for the schema deviations from docs/generated/04_DATA_MODEL_CATALOGUE.md.

Both owned entities (`genealogy_node`, `genealogy_edge`) are DDL-ready -- the best ratio of any module
built so far. Per Document 13 §8 ("Write Path"), genealogy rows are meant to be generated by domain events
(MaterialConsumed, DrugBatchProduced, DeviceComponentAssembled, FillLinkedToDevice, PackagingCompleted,
DistributionLinked) from other modules, not by a public write API -- there is no POST /genealogy/v1/nodes
or /edges endpoint in the document's own 8-API list. None of those named events exist yet: Material
Service is WP-04 (not built), and batch_execution/device (Documents 11/12) emit differently-named events
(BatchIssued, DeviceUnitCreated, ...) that don't map onto them. This pass therefore builds the graph
engine itself (node/edge creation, correction, consistency/cycle rules, traversal queries) as internal
service functions with no public write endpoint -- exactly matching the document's own exposure boundary
-- and leaves real event-driven population for whenever those producers exist (SG-052). The 5 read-only
query APIs are built and exposed. `POST /genealogy/v1/impact-assessments` and `POST /genealogy/v1/exports`
have no backing entity anywhere in the data model catalogue (only 2 entities are owned by this module) --
deferred (SG-051).
"""

