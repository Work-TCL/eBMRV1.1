# GEN-FR-024: rework/correction relationships are separately typed precisely so cycle detection over
# normal ancestry can ignore them -- REWORKED_FROM/SUPERSEDES legitimately point backward without
# implying an ancestry cycle.
ANCESTRY_EDGE_TYPES = tuple(t for t in EDGE_TYPES if t not in ("REWORKED_FROM", "SUPERSEDES"))

EDGE_STATES = ("ACTIVE", "SUPERSEDED", "VOIDED")


class GenealogyNode(Base):
    """No `version`/`state` column in the source DDL -- nodes are pure insert-only facts (GEN-FR-016);
    only edges are ever superseded (GEN-FR-017)."""

    __tablename__ = "genealogy_node"
    __table_args__ = {"schema": "ebmr"}

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    site_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), ForeignKey("iam.sites.id"), nullable=False)
    node_type: Mapped[str] = mapped_column(String(60), nullable=False)
    business_ref: Mapped[str | None] = mapped_column(String(200))
    authoritative_record_type: Mapped[str | None] = mapped_column(String(80))
    authoritative_record_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True))
    authoritative_version: Mapped[int | None] = mapped_column()
    record_hash: Mapped[str | None] = mapped_column(String(64))
    created_at: Mapped[datetime] = mapped_column(server_default=func.now())


class GenealogyEdge(Base):
    __tablename__ = "genealogy_edge"
    __table_args__ = (
        UniqueConstraint("from_node_id", "to_node_id", "edge_type", "source_event_id"),
        {"schema": "ebmr"},
    )

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    from_node_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), ForeignKey("ebmr.genealogy_node.id"), nullable=False)
    to_node_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), ForeignKey("ebmr.genealogy_node.id"), nullable=False)
    edge_type: Mapped[str] = mapped_column(String(60), nullable=False)
    quantity: Mapped[Decimal | None] = mapped_column(Numeric(24, 8))
    uom: Mapped[str | None] = mapped_column(String(40))
    # SG-146 (remainder, module 4 of 8), MIG-FR-004 expand step: dual-written best-effort, backfillable
    # (ebmr.genealogy_edge is mutable — UPDATE granted, migration 5e23e1067790 0014).
    uom_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True), ForeignKey("rules.gxp_uom.uom_id"))
    step_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True))
    source_event_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True))
    state: Mapped[str] = mapped_column(String(30), nullable=False, default="ACTIVE")
    supersedes_edge_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True), ForeignKey("ebmr.genealogy_edge.id"))
    created_at: Mapped[datetime] = mapped_column(server_default=func.now())
